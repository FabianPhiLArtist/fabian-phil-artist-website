const encodeStrict = (value) =>
  encodeURIComponent(value).replace(/[!'()*]/g, (c) => `%${c.charCodeAt(0).toString(16).toUpperCase()}`)

// Old paths are matched both as browsers usually send them (spaces as %20) and fully
// encoded ($ & ' as %24 %26 %27).
const toRedirects = (dir, pairs) =>
  pairs.flatMap(([from, to]) => {
    const destination = `/${dir}/artworks/${to}`
    const sources = new Set([
      encodeURI(`/${dir}/artworks/${from}`),
      `/${dir}/artworks/${encodeStrict(from)}`,
    ])
    return [...sources].map((source) => ({ source, destination, statusCode: 301 }))
  })

module.exports = [
  ...toRedirects('images', renames.images),
  ...toRedirects('videos', renames.videos),
  ...toRedirects('images', renames.secondaryImages),
]
