// The selected option label, or empty when nothing valid was chosen.
// Unknown values are dropped here so a studio address cannot replace the choice.
export function collectorLocationLabel(locale: Locale, value: string): string {
  const label = value.trim()
  return collectorLocationOptions[locale].includes(label) ? label : ''
}
